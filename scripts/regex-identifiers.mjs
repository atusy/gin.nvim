// Test-only Unicode property table for the experimental ECMAScript matcher.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const tables = [];
for (const property of ['ID_Start', 'ID_Continue']) {
  const regex = new RegExp(`^\\p{${property}}$`, 'u');
  const ranges = [];
  let first;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const matches = cp < 0x110000 && regex.test(String.fromCodePoint(cp));
    if (matches && first === undefined) first = cp;
    if (!matches && first !== undefined) {
      ranges.push(`    { 0x${first.toString(16).toUpperCase()}, 0x${(cp - 1).toString(16).toUpperCase()} },`);
      first = undefined;
    }
  }
  tables.push(`  ${property} = {\n${ranges.join('\n')}\n  },`);
}
const serialized = `-- Generated by scripts/regex-identifiers.mjs; Unicode ${process.versions.unicode}.\n-- stylua: ignore\nreturn {\n${tables.join('\n')}\n}\n`;
const path = fileURLToPath(new URL('../tests/audit/unicode_identifiers.lua', import.meta.url));
if (process.argv[2] === '--write') writeFileSync(path, serialized);
else if (process.argv[2] !== '--check') throw new Error('usage: node scripts/regex-identifiers.mjs --write|--check');
else if (readFileSync(path, 'utf8') !== serialized) throw new Error('Unicode identifier table changed; inspect before regenerating');
console.log(`Unicode ${process.versions.unicode} identifier ranges verified`);
