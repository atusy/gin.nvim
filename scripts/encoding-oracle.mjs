// Development-only TextDecoder oracle; production decoding is Lua-only.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const labels = readFileSync(root + 'tests/audit/encoding-labels.json', 'utf8');
const hash = createHash('sha256').update(labels).digest('hex');
const lock = JSON.parse(readFileSync(root + 'deps-lock.json'));
const head = execFileSync('git', ['-C', root + '.deps/vim-gin', 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (head !== lock['vim-gin'].commit) throw new Error('vim-gin checkout does not match deps-lock.json');
const header = `-- Generated by scripts/encoding-oracle.mjs (Deno ${Deno.version.deno}).\n-- https://encoding.spec.whatwg.org/encodings.json SHA256 ${hash}\n`;
let aliases = header + 'return {\n', single = header + 'return {\n';
const records = [];
function decode(name, bytes, fatal = true) {
  try { return { text: new TextDecoder(name, { fatal }).decode(Uint8Array.from(bytes)) }; }
  catch { return { error: true }; }
}
const unicodeCases = [[], [65], [65, 0], [0, 65], [255, 254], [254, 255], [239, 187, 191], [240, 159, 152, 128], [61, 216, 0, 222], [216, 61, 222, 0], [0, 216], [0, 220], [237, 160, 128], [192, 175], [0, 10]];
for (const group of JSON.parse(labels)) for (const encoding of group.encodings) {
  let canonical;
  try { canonical = new TextDecoder(encoding.name).encoding; } catch { continue; }
  for (const label of encoding.labels) aliases += `[${JSON.stringify(label)}] = ${JSON.stringify(canonical)},\n`;
  if (group.heading === 'Legacy single-byte encodings' || canonical === 'x-user-defined') {
    const bytes = Array.from({ length: 256 }, (_, byte) => decode(canonical, [byte]));
    single += `[${JSON.stringify(canonical)}] = {${bytes.slice(128).map(value => value.error ? 'false' : value.text.codePointAt(0)).join(',')}},\n`;
    records.push({ encoding: canonical, aliases: encoding.labels, cases: bytes.map((value, byte) => ({ bytes: [byte], ...value })) });
  } else if (canonical.startsWith('utf-')) {
    records.push({ encoding: canonical, aliases: encoding.labels, cases: unicodeCases.map(bytes => ({ bytes, ...decode(canonical, bytes) })) });
  }
}
function lua(source) {
  return execFileSync('stylua', ['--config-path', root + '.stylua.toml', '-'], { input: source, encoding: 'utf8' });
}
const outputs = {
  'lua/gin/encoding/labels.lua': lua(aliases + '}\n'),
  'lua/gin/encoding/single_byte.lua': lua(single + '}\n'),
  'tests/audit/encoding-oracle.json': JSON.stringify({ upstream: head, labels_sha256: hash }).slice(0, -1) + ',"records":[\n' + records.map(value => JSON.stringify(value)).join(',\n') + ']}\n',
};
for (const [path, contents] of Object.entries(outputs)) {
  if (Deno.args[0] === '--write') writeFileSync(root + path, contents);
  else if (Deno.args[0] === '--check') {
    if (readFileSync(root + path, 'utf8') !== contents) throw new Error(`${path} differs from TextDecoder oracle`);
  } else throw new Error('usage: deno run --allow-read --allow-write --allow-run --allow-env scripts/encoding-oracle.mjs --write|--check');
}
console.log(`${records.length} encoding families generated/verified at ${head}`);
