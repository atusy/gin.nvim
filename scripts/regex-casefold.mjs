// ECMAScript Canonicalize for UTF-16 (without u/v), not Unicode simple folding.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const entries = [];
for (let cp = 0; cp <= 0xffff; cp++) {
  const upper = String.fromCharCode(cp).toUpperCase();
  if (upper.length !== 1) continue;
  const canonical = upper.charCodeAt(0);
  if (canonical === cp || (cp >= 128 && canonical < 128)) continue;
  entries.push(`  [0x${cp.toString(16).toUpperCase()}] = 0x${canonical.toString(16).toUpperCase()},`);
}
const serialized = `-- Generated by scripts/regex-casefold.mjs; Unicode ${process.versions.unicode}.\n-- stylua: ignore\nreturn {\n${entries.join('\n')}\n}\n`;
const path = fileURLToPath(new URL('../lua/gin/regex_casefold.lua', import.meta.url));
if (process.argv[2] === '--write') writeFileSync(path, serialized);
else if (process.argv[2] !== '--check') throw new Error('usage: node scripts/regex-casefold.mjs --write|--check');
else if (readFileSync(path, 'utf8') !== serialized) throw new Error('Case canonicalization changed; inspect before regenerating');
console.log(`Unicode ${process.versions.unicode} non-Unicode regex case table verified`);
